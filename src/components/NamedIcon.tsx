export function NamedIcon({
  name,
  size,
  className,
}: {
  name?: string | null;
  size?: number | string;
  className?: string;
}) {
  const Icon = ICONS[name || ""] ?? MessageSquare;
  return <Icon size={size} className={className} />;
}
