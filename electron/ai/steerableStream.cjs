/** SDK owns tool loops; this coordinator only continues naturally completed SDK runs. */
const { isContextWindowError } = require('./contextCompaction.cjs');

function createSteerableStream({ createAgent, messages, maxTurns, signal, inputs, compactor }) {
  let resolveUsage;
  let rejectUsage;
  const usagePromise = new Promise((resolve, reject) => { resolveUsage = resolve; rejectUsage = reject; });
  // The manager awaits usage after draining the stream; avoid an unhandled rejection on stream errors.
  usagePromise.catch(() => {});
  const ledger = [...messages];
  let usedSteps = 0;
  let segment = 0;
  let cancelled = false;
  let reader;
  let overflowRetried = false;
  const total = { promptTokens: 0, completionTokens: 0 };
  const stream = new ReadableStream({
    async start(controller) {
      try {
        let finish;
        do {
          let responseCount = 0;
          const injectionBatches = [];
          const agent = createAgent({
            remainingTurns: maxTurns - usedSteps,
            prepareStep: async () => {
              signal?.throwIfAborted();
              const pending = inputs?.consume() || { messages: [], items: [] };
              ledger.push(...pending.messages);
              const batch = [];
              if (pending.items.length) batch.push({ type: 'agent-input', items: pending.items });
              // Queue before awaiting: consumed inputs remain visible even if summary fails.
              injectionBatches.push(batch);
              const replacement = await compactor?.prepare(ledger);
              signal?.throwIfAborted();
              if (replacement) {
                ledger.splice(0, ledger.length, ...replacement.messages);
                batch.push({ type: 'context-checkpoint', checkpoint: replacement.checkpoint });
              }
              return { messages: [...ledger] };
            },
            onStepFinish: (step) => {
              // SDK response.messages is cumulative within this invocation, excluding prepareStep overrides.
              ledger.push(...step.response.messages.slice(responseCount));
              responseCount = step.response.messages.length;
              usedSteps++;
              compactor?.recordUsage(step.usage);
            },
          });
          const result = await agent.stream({ messages: [...ledger], abortSignal: signal });
          reader = result.toUIMessageStream({ onError: (err) => err instanceof Error ? err.message : String(err) }).getReader();
          let hadError = false;
          let errorChunk;
          let canRetryError = false;
          let stepProducedOutput = false;
          const flushBatches = () => {
            for (const batch of injectionBatches.splice(0)) for (const chunk of batch) controller.enqueue(chunk);
          };
          while (!cancelled) {
            const { done, value } = await reader.read();
            if (done) break;
            if (segment > 0 && value.type === 'start') continue;
            if (value.type === 'start-step') {
              stepProducedOutput = false;
              for (const chunk of injectionBatches.shift() || []) controller.enqueue(chunk);
            }
            if (value.type === 'finish') { finish = value; continue; }
            if (value.type === 'error') { hadError = true; errorChunk = value; canRetryError = !stepProducedOutput; continue; }
            if (value.type === 'finish-step') stepProducedOutput = false;
            if (value.type === 'text-delta' || value.type.startsWith('tool-input')) stepProducedOutput = true;
            // IDs generated by separate SDK invocations may collide.
            const chunk = value.id ? { ...value, id: `${segment}:${value.id}` } : value;
            controller.enqueue(chunk);
          }
          reader.releaseLock();
          reader = null;
          flushBatches();
          signal?.throwIfAborted();
          const usage = await result.totalUsage.catch(() => null);
          total.promptTokens += usage?.inputTokens || 0;
          total.completionTokens += usage?.outputTokens || 0;
          if (hadError && canRetryError && compactor && !overflowRetried && !signal?.aborted && isContextWindowError(errorChunk)) {
            overflowRetried = true;
            // The ledger already includes completed steps and their tool results.
            // Restart only the rejected model call, never earlier tool executions.
            const replacement = await compactor.compact(ledger, 'overflow');
            signal?.throwIfAborted();
            if (replacement) {
              ledger.splice(0, ledger.length, ...replacement.messages);
              controller.enqueue({ type: 'context-checkpoint', checkpoint: replacement.checkpoint });
              segment++;
              finish = undefined;
              continue;
            }
          }
          if (errorChunk) controller.enqueue(errorChunk);
          if (cancelled || signal?.aborted || hadError || usedSteps >= maxTurns || !inputs?.hasPending()) break;
          segment++;
        } while (true);
        // Seal synchronously with the last queue check. IPC cannot enqueue into a completed execution.
        inputs?.seal();
        if (!cancelled) {
          controller.enqueue({ ...(finish || { type: 'finish', finishReason: 'stop' }),
            finishReason: usedSteps >= maxTurns && inputs?.hasPending() ? 'tool-calls' : finish?.finishReason || 'stop' });
          controller.close();
        }
        resolveUsage(total);
      } catch (err) {
        inputs?.seal();
        if (!cancelled) controller.error(err);
        rejectUsage(err);
      } finally {
        reader?.releaseLock();
      }
    },
    async cancel(reason) {
      cancelled = true;
      inputs?.seal();
      await reader?.cancel(reason);
    },
  });
  return { stream, usagePromise };
}
module.exports = { createSteerableStream };
